function tableOfTypes() {
  return '<table class="data"><thead><tr><th>Type</th><th class="num">Cost</th><th class="num">P(s)</th><th class="num">Rig d</th></tr></thead><tbody>' +
    Object.values(OPP_TYPES).map(t => `<tr><td>${t.label}</td><td class="num">$${(t.cost / 1e6).toFixed(2)}M</td><td class="num">${Math.round(t.ps * 100)}%</td><td class="num">${t.rig}</td></tr>`).join('') +
    '</tbody></table>'
}

export function openMethods(route: Route) {
  const scrim = h('div', { class: 'drawer-scrim' })
  const drawer = h('aside', { class: 'drawer', role: 'dialog', 'aria-modal': 'true', 'aria-label': 'Methods' })
  const close = () => { scrim.classList.remove('on'); drawer.classList.remove('on'); setTimeout(() => { scrim.remove(); drawer.remove() }, 300); removeEventListener('keydown', onKey) }
  const onKey = (e: KeyboardEvent) => { if (e.key === 'Escape') close() }
  const btn = h('button', { class: 'btn close', onclick: close }, 'Close ✕')
  drawer.append(btn, h('div', { html: SECTIONS[route] + COMMON + REFS }))
  scrim.addEventListener('click', close)
  addEventListener('keydown', onKey)
  document.body.append(scrim, drawer)
  requestAnimationFrame(() => { scrim.classList.add('on'); drawer.classList.add('on'); btn.focus() })
}

